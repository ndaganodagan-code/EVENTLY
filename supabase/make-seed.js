// Builds supabase/seed.sql from the site's Evently/data.js.
// Run: node supabase/make-seed.js
// Demo events and demo deals are left out: the database holds real listings only.
const fs = require("fs"), path = require("path"), vm = require("vm");

const win = {};
vm.runInNewContext(fs.readFileSync(path.join(__dirname, "../Evently/data.js"), "utf8"), { window: win, Set });

const q = v => v == null ? "null" : "'" + String(v).replace(/'/g, "''") + "'";
const j = v => v == null ? "null" : q(JSON.stringify(v)) + "::jsonb";
const arr = a => "array[" + (a || []).map(q).join(",") + "]::text[]";
const ts = s => s ? q(s.length === 16 ? s + ":00+03:00" : s) : "null"; // site times are Kampala local

const out = ["-- Generated by supabase/make-seed.js from Evently/data.js. Do not edit by hand.", "begin;"];

win.EVENTLY_CATEGORIES.forEach((c, i) =>
  out.push(`insert into categories (id,name,blurb,virtual,sort) values (${q(c.id)},${q(c.name)},${q(c.blurb)},${!!c.virtual},${i}) on conflict (id) do update set name=excluded.name, blurb=excluded.blurb, virtual=excluded.virtual, sort=excluded.sort;`));

const vRows = Object.entries(win.EVENTLY_VENUES).filter(([n]) => !/Demo/.test(n))
  .map(([n, v]) => `(${q(n)},${q(v.area)},${v.lat ?? "null"},${v.lng ?? "null"})`);
out.push(`insert into venues (name,area,lat,lng) values\n${vRows.join(",\n")}\non conflict (name) do update set area=excluded.area, lat=excluded.lat, lng=excluded.lng;`);

const evRows = []; let evCols;
const real = win.EVENTLY_SEED.filter(e => e.verify !== "demo" && e.start);
const posters = win.EVENTLY_POSTERS || new Set();
for (const e of real) {
  const cols = {
    slug: q(e.slug), title: q(e.title), cat: q(e.cat), tags: arr(e.tags), artists: arr(e.artists),
    start_at: ts(e.start), end_at: ts(e.end), time_tbc: !!e.timeTBC, recurring: q(e.recurring ? JSON.stringify(e.recurring) : null),
    venue: q(e.venue), city: q(e.city || "Kampala"), price: j(e.price || {}), organizer: q(e.organizer || ""),
    description: q(e.desc || ""), sources: j(e.sources || []), tickets: j(e.tickets), tickets_note: q(e.ticketsNote),
    poster_path: q(posters.has(e.slug) ? e.slug + ".webp" : null), verify: q(e.verify || "partial"),
    status: q(e.status || "scheduled"), status_note: q(e.statusNote), community: !!e.community, featured: !!e.featured,
    base_score: e.base || 0, review: "'approved'", added: q(e.added || "2026-11-26")
  };
  evCols = Object.keys(cols);
  evRows.push("(" + evCols.map(x => cols[x]).join(",") + ")");
}
out.push(`insert into events (${evCols.join(",")}) values\n${evRows.join(",\n")}\non conflict (slug) do update set ${evCols.filter(x => x !== "slug").map(x => `${x}=excluded.${x}`).join(", ")};`);

const slugs = new Set(real.map(e => e.slug));
for (const d of win.EVENTLY_DEALS) {
  if (d.verify === "demo" || !d.until) continue;
  out.push(`insert into deals (id,event_slug,kind,title,description,until,until_note,source,verify) values (${q(d.id)},${slugs.has(d.slug) ? q(d.slug) : "null"},${q(d.kind)},${q(d.title)},${q(d.desc)},${ts(d.until)},${q(d.untilNote)},${q(d.source)},${q(d.verify)}) on conflict (id) do update set kind=excluded.kind, title=excluded.title, description=excluded.description, until=excluded.until, until_note=excluded.until_note, source=excluded.source;`);
}

out.push("commit;");
fs.writeFileSync(path.join(__dirname, "seed.sql"), out.join("\n") + "\n");
console.log(`seed.sql: ${win.EVENTLY_CATEGORIES.length} categories, ${real.length} events`);
